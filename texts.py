def t(key, lang="uz", **kwargs):
    """6 til uchun matn. Fallback zanjiri: lang → en → uz → kalit."""
    lang = str(lang).lower()
    d = TEXTS.get(lang) or TEXTS.get("en") or TEXTS["uz"]
    txt = d.get(key) or TEXTS.get("en", {}).get(key) or TEXTS["uz"].get(key, key)
